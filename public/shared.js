  var GRAVITY = 0.42;
  var MAXFALL = 7.0;
  var MOVE = 1.75;
  var JUMP = -7.6;      // 점프 높이 약 69px (발판 간격 48px를 여유 있게 넘는다)
  var COYOTE = 5;       // 발판에서 막 벗어난 직후 몇 프레임까지는 점프를 받아준다

  var PW = 12, PH = 14;   // 플레이어 히트박스
  var EW = 13, EH = 14;   // 적 히트박스
